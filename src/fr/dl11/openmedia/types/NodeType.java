package fr.dl11.openmedia.types;

/**
 * Enumeration representing different types of nodes.
 *
 * <p>The {@code NodeType} enum defines constants for various node types
 * that can be used in the application. It includes predefined types such as
 * {@code kPerson}, {@code kMedia}, and {@code kOrganization}.</p>
 */
public enum NodeType {
    /**
     * Represents a person node type.
     */
    kPerson,

    /**
     * Represents a media node type.
     */
    kMedia,

    /**
     * Represents an organization node type.
     */
    kOrganization,
}